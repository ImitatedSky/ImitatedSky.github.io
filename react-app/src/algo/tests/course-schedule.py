s = Solution()
check(s.canFinish(2, [[1, 0]]), True, "範例 1")
check(s.canFinish(2, [[1, 0], [0, 1]]), False, "範例 2：兩門課互為先修")
check(s.canFinish(1, []), True, "只有一門課")
check(s.canFinish(3, []), True, "沒有任何先修關係")
check(s.canFinish(5, [[1, 0], [2, 0], [3, 1], [3, 2], [4, 3]]), True, "菱形 DAG：同一個點從兩條路走到")
check(s.canFinish(4, [[1, 0], [2, 1], [3, 2], [1, 3]]), False, "環不包含起點")
check(s.canFinish(3, [[0, 1], [1, 2], [2, 0]]), False, "三門課繞成一圈")
check(s.canFinish(6, [[1, 0], [3, 2], [5, 4]]), True, "不連通的三條邊")
check(s.canFinish(6, [[1, 0], [2, 1], [4, 3], [5, 4], [3, 5]]), False, "環藏在另一個連通區塊")
check(s.canFinish(4, [[1, 0], [2, 0], [3, 0], [2, 1], [3, 1], [3, 2]]), True, "邊很多但沒有環")
check(s.canFinish(200, [[i + 1, i] for i in range(199)]), True, "200 門課排成一條鏈")
check(s.canFinish(200, [[i + 1, i] for i in range(199)] + [[0, 199]]), False, "200 門課繞成一個大環")
