def run(equations, values, queries):
    got = Solution().calcEquation(equations, values, queries)
    # 浮點數乘除會有極小的誤差，四捨五入到小數 5 位再比
    return [round(float(x), 5) for x in got]


check(
    run([["a", "b"], ["b", "c"]], [2.0, 3.0], [["a", "c"], ["b", "a"], ["a", "e"], ["a", "a"], ["x", "x"]]),
    [6.0, 0.5, -1.0, 1.0, -1.0],
    "範例 1",
)
check(
    run(
        [["a", "b"], ["b", "c"], ["bc", "cd"]],
        [1.5, 2.5, 5.0],
        [["a", "c"], ["c", "b"], ["bc", "cd"], ["cd", "bc"]],
    ),
    [3.75, 0.4, 5.0, 0.2],
    "範例 2",
)
check(
    run([["a", "b"]], [0.5], [["a", "b"], ["b", "a"], ["a", "c"], ["x", "y"]]),
    [0.5, 2.0, -1.0, -1.0],
    "範例 3：只有一個等式",
)
check(
    run([["a", "b"], ["c", "d"]], [2.0, 4.0], [["a", "d"], ["b", "c"], ["c", "d"], ["d", "c"]]),
    [-1.0, -1.0, 4.0, 0.25],
    "兩個不相連的區塊",
)
check(
    run([["a", "b"]], [3.0], [["a", "a"], ["b", "b"], ["z", "z"]]),
    [1.0, 1.0, -1.0],
    "自己除以自己：出現過才是 1.0",
)
check(
    run(
        [["a", "b"], ["b", "c"], ["c", "d"], ["d", "e"]],
        [2.0, 3.0, 4.0, 5.0],
        [["a", "e"], ["e", "a"], ["b", "d"], ["d", "b"]],
    ),
    [120.0, round(1 / 120, 5), 12.0, round(1 / 12, 5)],
    "一條長鏈，正反方向都要能算",
)
check(
    run(
        [["x1", "x2"], ["x2", "x3"], ["x1", "x4"], ["x2", "x5"]],
        [3.0, 0.5, 3.4, 5.6],
        [["x2", "x4"], ["x1", "x5"], ["x1", "x3"], ["x5", "x5"], ["x5", "x1"], ["x3", "x4"], ["x4", "x3"], ["x6", "x6"], ["x0", "x0"]],
    ),
    [1.13333, 16.8, 1.5, 1.0, 0.05952, 2.26667, 0.44118, -1.0, -1.0],
    "樹狀關係，多字元變數名",
)
check(
    run([["a", "b"], ["b", "c"], ["a", "c"]], [2.0, 3.0, 6.0], [["c", "a"], ["a", "c"]]),
    [round(1 / 6, 5), 6.0],
    "有環（等式彼此一致）",
)
