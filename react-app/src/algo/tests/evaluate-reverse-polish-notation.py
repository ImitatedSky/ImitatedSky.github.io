s = Solution()
check(s.evalRPN(["2", "1", "+", "3", "*"]), 9, "範例 1：(2 + 1) * 3")
check(s.evalRPN(["4", "13", "5", "/", "+"]), 6, "範例 2：4 + 13 / 5")
check(
    s.evalRPN(["10", "6", "9", "3", "+", "-11", "*", "/", "*", "17", "+", "5", "+"]),
    22,
    "範例 3：長算式",
)
check(s.evalRPN(["42"]), 42, "只有一個數字")
check(s.evalRPN(["-7"]), -7, "只有一個負數")
check(s.evalRPN(["5", "3", "-"]), 2, "減法的順序：5 - 3")
check(s.evalRPN(["3", "5", "-"]), -2, "減法得到負數")
check(s.evalRPN(["7", "2", "/"]), 3, "正數除法捨去小數")
check(s.evalRPN(["-7", "2", "/"]), -3, "負數除法向零截斷（不是 -4）")
check(s.evalRPN(["7", "-2", "/"]), -3, "除數為負，同樣向零截斷")
check(s.evalRPN(["-7", "-2", "/"]), 3, "負負得正")
check(s.evalRPN(["1", "-3", "/"]), 0, "絕對值小於 1 的商是 0")
check(s.evalRPN(["4", "-13", "5", "/", "+"]), 2, "4 + (-13 / 5)")
check(s.evalRPN(["2", "3", "4", "*", "+"]), 14, "2 + 3 * 4")
check(s.evalRPN(["1"] + ["1", "+"] * 4999), 5000, "很長的算式")
