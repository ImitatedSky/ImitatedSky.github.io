s = Solution()
check(s.canJump([2, 3, 1, 1, 4]), True, "範例 1")
check(s.canJump([3, 2, 1, 0, 4]), False, "範例 2")
check(s.canJump([0]), True, "只有一格，起點就是終點")
check(s.canJump([0, 1]), False, "起點就跳不動")
check(s.canJump([1, 0, 2]), False, "中間被 0 擋住")
check(s.canJump([2, 0, 0]), True, "剛好跳過 0")
check(s.canJump([1, 1, 1, 1]), True, "每次只能跳一格")
check(s.canJump([5, 0, 0, 0, 0, 0]), True, "一步到底")
check(s.canJump([4, 0, 0, 0, 0, 0]), False, "差一格")
check(s.canJump([1] * 2000 + [0, 0]), False, "較長的輸入")
