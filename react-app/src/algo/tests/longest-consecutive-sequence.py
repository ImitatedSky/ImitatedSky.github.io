s = Solution()
check(s.longestConsecutive([100, 4, 200, 1, 3, 2]), 4, "範例 1")
check(s.longestConsecutive([0, 3, 7, 2, 5, 8, 4, 6, 0, 1]), 9, "範例 2")
check(s.longestConsecutive([1, 0, 1, 2]), 3, "有重複的數字")
check(s.longestConsecutive([]), 0, "空陣列")
check(s.longestConsecutive([7]), 1, "單一元素")
check(s.longestConsecutive([5, 5, 5]), 1, "全部相同")
check(s.longestConsecutive([10, 20, 30]), 1, "完全不連續")
check(s.longestConsecutive([-2, -1, 0, 1, 5]), 4, "跨越負數與 0")
check(s.longestConsecutive([5, 1, 6, 2, 9, 1, 7]), 3, "兩段，後面那段比較長")
check(s.longestConsecutive([1000000000, -1000000000, 999999999]), 2, "極大與極小的數值")
# 效能：O(n²) 的寫法（沒有判斷起點）在這裡會跑非常久
check(s.longestConsecutive(list(range(100000, 0, -1))), 100000, "十萬個連續數字（倒序）")
check(s.longestConsecutive([0] * 50000 + list(range(1, 50001))), 50001, "大量重複的起點")
