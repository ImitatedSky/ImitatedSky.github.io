def _merge(intervals):
    # 題目不要求輸出順序，排序後再比較
    return sorted(list(x) for x in Solution().merge(intervals))


check(_merge([[1, 3], [2, 6], [8, 10], [15, 18]]), [[1, 6], [8, 10], [15, 18]], "範例 1")
check(_merge([[1, 4], [4, 5]]), [[1, 5]], "範例 2：端點相碰")
check(_merge([[1, 4]]), [[1, 4]], "只有一個區間")
check(_merge([[1, 10], [2, 3], [4, 5]]), [[1, 10]], "大區間包住小區間，終點要取 max")
check(_merge([[5, 7], [1, 4], [2, 3], [4, 6], [9, 10]]), [[1, 7], [9, 10]], "未排序的輸入")
check(_merge([[1, 2], [3, 4], [5, 6]]), [[1, 2], [3, 4], [5, 6]], "完全不重疊")
check(_merge([[2, 3], [2, 2], [3, 3], [1, 3], [5, 7], [2, 2], [4, 6]]), [[1, 3], [4, 7]], "長度為 0 的區間與重複")
check(_merge([[0, 0], [0, 0]]), [[0, 0]], "相同的點區間")
check(_merge([[1, 4], [0, 4]]), [[0, 4]], "後面的起點比較小")
check(_merge([[i, i + 1] for i in range(0, 2000)]), [[0, 2000]], "連成一長串")
